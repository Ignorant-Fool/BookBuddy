# ============================================================ 问题分析 / 检索规划
CLASSIFY_PROMPT = """{dialogue}分析用户的阅读问题，输出检索计划。

用户问题: {query}

请严格输出如下 JSON（不要输出任何其他内容）:
{{
  "type": "事实查询|定义解释|对比分析|复杂推理|列举梳理|时间线",
  "entities": ["问题中的关键实体，如人物名、地点、事件名"],
  "strategies": [
    {{"label": "策略说明", "mode": "semantic|keyword|scan", "query": "实际检索语句"}}
  ]
}}

指代消解（重要）：
- 如果问题里出现"她/他/它/这个人/刚才那个/上面说的/那本书"等代词，必须结合对话历史
  替换成具体的人名或事物；entities 与 strategies.query 都要用替换后的说法
- 例如上一轮在讨论林黛玉，本轮问"她母亲是谁"，则实体应为"林黛玉"，检索语句为"林黛玉 母亲"

策略规则：
- 事实查询 / 定义解释：1 条 semantic 策略，query 用原问题（已消解代词）
- 对比分析：每个实体 1 条 keyword 策略，再加 1 条 semantic 策略做对比
- 复杂推理 / 列举梳理 / 时间线：拆成 2-4 条 semantic 子策略，每条对应一个子问题
- 涉及"第一次出场/最早出现/最后一次"：必须包含 1 条 scan 策略，query 只写实体名

只输出 JSON。"""

# ============================================================ 证据充分性评估
EVIDENCE_PROMPT = """判断下面的证据片段是否足以回答用户问题。

用户问题: {query}

证据片段:
{context}

只输出 JSON:
{{"sufficient": true 或 false, "missing": ["还缺什么信息的检索语句"]}}

规则：
- 只要片段中包含能支撑回答的关键信息（哪怕不完整、需要归纳），sufficient 就为 true
- 只有在片段与问题明显无关、或完全缺少回答所需的关键事实时，才判为 false
- 若只覆盖了问题的一部分，sufficient 为 false，missing 给出最多 2 条补充检索语句
- missing 里只能写"用于检索书籍原文的关键词式语句"，绝对不要反问用户，
  也不要写"请问您指的是谁"这类内容

只输出 JSON。"""

